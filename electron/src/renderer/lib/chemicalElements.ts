export const ELEMENTS_BY_ATOMIC_NUMBER: Readonly<Record<number, string>> = Object.fromEntries(
  Array.from(ELEMENT_SYMBOLS.entries())
    .filter(([atomicNumber, symbol]) => atomicNumber > 0 && symbol.length > 0)
    .map(([atomicNumber, symbol]) => [atomicNumber, symbol]),
);

export const ATOMIC_NUMBERS_BY_ELEMENT: Readonly<Record<string, number>> = Object.fromEntries(
  Array.from(ELEMENT_SYMBOLS.entries())
    .filter(([atomicNumber, symbol]) => atomicNumber > 0 && symbol.length > 0)
    .map(([atomicNumber, symbol]) => [symbol, atomicNumber]),
);
